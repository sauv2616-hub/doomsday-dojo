#!/usr/bin/env python3
"""Build facts.js for the Daily Three from data/facts.txt.

- Converts Julian (old-style) dates, marked with a trailing J, to the Gregorian calendar.
- Validates every line (real date, known category, no duplicates).
- Keeps data/schedule.txt stable: already-scheduled facts never move, new facts are
  appended in groups of three with mixed categories. Puzzle #n uses schedule entries
  3(n-1) .. 3(n-1)+2, so adding facts never changes past or current puzzles.
"""
import datetime, json, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'data', 'facts.txt')
SCHED = os.path.join(HERE, 'data', 'schedule.txt')
OUT = os.path.join(HERE, 'facts.js')
CATS = set('hspkcbf')


def julian_to_gregorian(y, m, d):
    a = (14 - m) // 12
    yy, mm = y + 4800 - a, m + 12 * a - 3
    jdn = d + (153 * mm + 2) // 5 + 365 * yy + yy // 4 - 32083
    return datetime.date.fromordinal(jdn - 1721425)  # JDN of 0001-01-01 (Gregorian) is 1721426


def parse():
    facts, errors, seen = [], [], set()
    for n, line in enumerate(open(SRC, encoding='utf-8'), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        try:
            ds, cat, text = line.split('|', 2)
        except ValueError:
            errors.append(f'line {n}: expected DATE|CAT|TEXT'); continue
        julian = ds.endswith('J')
        y, m, d = map(int, ds.rstrip('J').split('-'))
        try:
            g = julian_to_gregorian(y, m, d) if julian else datetime.date(y, m, d)
            if julian:
                datetime.date(y, m, d) if not (m == 2 and d == 29) else None  # Julian Feb 29 is fine in any year divisible by 4
        except ValueError as e:
            errors.append(f'line {n}: bad date {ds} ({e})'); continue
        if cat not in CATS:
            errors.append(f'line {n}: unknown category {cat!r}'); continue
        if not text.strip() or len(text) > 140:
            errors.append(f'line {n}: text empty or over 140 characters'); continue
        key = f'{ds}|{text}'
        if key in seen:
            errors.append(f'line {n}: duplicate'); continue
        seen.add(key)
        facts.append({'key': key, 'g': g, 'cat': cat, 'text': text, 'j': (y, m, d) if julian else None})
    return facts, errors


def extend_schedule(facts):
    order = [k for k in open(SCHED, encoding='utf-8').read().splitlines() if k] if os.path.exists(SCHED) else []
    have = {f['key'] for f in facts}
    missing = [k for k in order if k not in have]
    if missing:
        sys.exit('These scheduled facts were removed or edited; restore them or edit schedule.txt by hand:\n  ' + '\n  '.join(missing))
    pool = [f for f in facts if f['key'] not in set(order)]
    random.Random(len(order) * 7919 + 20261029).shuffle(pool)
    added = 0
    while pool:
        group = [pool.pop(0)]
        while len(group) < 3 and pool:
            # next fact whose category (and century) isn't already in this day's group
            pick = next((i for i, f in enumerate(pool) if f['cat'] not in {x['cat'] for x in group}
                         and f['g'].year // 100 not in {x['g'].year // 100 for x in group}), None)
            if pick is None:
                pick = next((i for i, f in enumerate(pool) if f['cat'] not in {x['cat'] for x in group}), 0)
            group.append(pool.pop(pick))
        order += [f['key'] for f in group]; added += len(group)
    with open(SCHED, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(order) + '\n')
    return order, added


def main():
    facts, errors = parse()
    if errors:
        sys.exit('\n'.join(errors))
    order, added = extend_schedule(facts)
    by_key = {f['key']: f for f in facts}
    rows = []
    for k in order:
        f = by_key[k]
        row = [f['g'].year, f['g'].month, f['g'].day, f['cat'], f['text']]
        if f['j']:
            row += list(f['j'])
        rows.append(row)
    body = ',\n'.join(json.dumps(r, ensure_ascii=False) for r in rows)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('// Generated by build_facts.py from data/facts.txt — edit that file, not this one.\n'
                 '// [year, month, day, category, fact, julianYear?, julianMonth?, julianDay?] in schedule order:\n'
                 '// Daily Three puzzle #n shows entries 3(n-1) .. 3(n-1)+2.\n'
                 f'const FACTS=[\n{body}\n];\n')
    days = len(order) // 3
    start = datetime.date(2026, 10, 29)
    print(f'{len(facts)} facts, {added} newly scheduled, {days} days of puzzles '
          f'(#1 {start} … #{days} {start + datetime.timedelta(days=days - 1)})')
    cats = {}
    for f in facts:
        cats[f['cat']] = cats.get(f['cat'], 0) + 1
    print('by category:', ', '.join(f'{c}={n}' for c, n in sorted(cats.items())))
    jul = [f for f in facts if f['j']]
    print(f'{len(jul)} Julian dates converted, e.g.',
          '; '.join(f"{f['j'][0]}-{f['j'][1]:02}-{f['j'][2]:02} → {f['g']}" for f in jul[:4]))


if __name__ == '__main__':
    main()
